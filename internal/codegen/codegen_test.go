func TestManglesGoKeywordsAndUsesVarForRuntimeConst(t *testing.T) {
	input := `
function value(): int { return 42; }
function package(type: int): int {
  const result: int = value();
  return type + result;
}
`
	tokens, _ := lexer.Lex("names.km", input)
	program, parseDiagnostics := parser.Parse(tokens)
	if len(parseDiagnostics) != 0 {
		t.Fatalf("parser diagnostics: %v", parseDiagnostics)
	}
	if diagnostics := sema.Check(program); len(diagnostics) != 0 {
		t.Fatalf("type diagnostics: %v", diagnostics)
	}
	generated, err := Generate(program, "sample")
	if err != nil {
		t.Fatal(err)
	}
	text := string(generated)
	for _, want := range []string{"func package_(type_ int) int", "var result int = value()", "return type_ + result"} {
		if !strings.Contains(text, want) {
			t.Errorf("generated Go does not contain %q:\n%s", want, text)
		}
	}
}

