func TestGenerateGolden(t *testing.T) {
	input := `
const meaning: int = 42;
function choose(flag: boolean, left: number, right: float): float64 {
  if (flag) { return left; } else { return right; }
}
`
	tokens, lexDiagnostics := lexer.Lex("golden.km", input)
	program, parseDiagnostics := parser.Parse(tokens)
	if len(lexDiagnostics)+len(parseDiagnostics) != 0 {
		t.Fatalf("frontend diagnostics: %v %v", lexDiagnostics, parseDiagnostics)
	}
	if diagnostics := sema.Check(program); len(diagnostics) != 0 {
		t.Fatalf("type diagnostics: %v", diagnostics)
	}
	generated, err := Generate(program, "sample")
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by ` + product.DisplayName + `. DO NOT EDIT.
package sample

const meaning int = 42

func choose(flag bool, left float64, right float64) float64 {
	if flag {
		return left
	} else {
		return right
	}
}
`
	if strings.TrimSpace(string(generated)) != strings.TrimSpace(want) {
		t.Fatalf("generated Go mismatch\n--- got ---\n%s\n--- want ---\n%s", generated, want)
	}
}

